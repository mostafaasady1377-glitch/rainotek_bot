      'اقساط ویژه، گارانتی کتبی و فرصت تست حضوری؛ شرایط را پیش از خرید بپرسید.',
      'برای درس، حسابداری و کار روزمره؛ انتخاب متناسب با بودجه شما.',
      'تعویض و معاوضه سیستم شما پس از کارشناسی؛ برای ارزیابی تماس بگیرید.',
      'انتخاب برای طراحی و تولید محتوا؛ اشانتیون خرید طبق شرایط فروشگاه.',
      'برای کار و پروژه، نقدی یا اقساطی؛ شرایط خرید را تلفنی هماهنگ کنید.',
      'تخفیف ویژه ۲۰ درصدی طبق شرایط جشنواره؛ مدل‌های مشمول را تلفنی بپرسید.',
      'با تست حضوری و گارانتی کتبی انتخاب کنید؛ شرایط اقساط با هماهنگی.',
